"""Collect the scan-check results (check/results/nN.tsv).
Sure fixes -> tools/fixes-scan.tsv (applied by tools/fix.py as its last step).
Unsure ones, paragraph-break notes and fixes whose find text is not in the book -> check/REPORT.md.
Usage: python -I tools/check-apply.py   (then: npm run text && npm run pdf)
"""
import glob, re

text = open('check/fixed-before-scan-check.md', encoding='utf-8').read()   # the text the helpers saw
sure, report, ok_pages, bad_lines = [], [], 0, 0
for f in sorted(glob.glob('check/results/n*.tsv'), key=lambda p: int(re.search(r'n(\d+)', p).group(1))):
    page = re.search(r'n(\d+)', f).group(1)
    lines = [l.rstrip('\n') for l in open(f, encoding='utf-8') if l.strip()]
    if lines == ['OK'] or not lines:
        ok_pages += 1
        continue
    for l in lines:
        if l.strip() == 'OK':
            continue
        parts = l.split('\t')
        if len(parts) < 3:
            report.append(f'- scan page {page}: could not read line: `{l}`')
            bad_lines += 1
            continue
        find, repl, conf = parts[0], parts[1], parts[2].strip().lower()
        note = parts[3] if len(parts) > 3 else ''
        if conf == 'sure' and repl != '?' and find != repl and text.count(find) == 1:
            sure.append((page, find, repl, note))
        else:
            why = 'not found in the text' if text.count(find) == 0 else ('found more than once' if text.count(find) > 1 else conf)
            report.append(f'- scan page {page} ({why}): “{find}” → “{repl}”. {note}')

with open('tools/fixes-scan.tsv', 'w', encoding='utf-8', newline='\n') as out:
    out.write('# page-by-page scan check (check/results), sure fixes only; regenerated by tools/check-apply.py\n')
    for page, find, repl, note in sure:
        out.write(f'{find}\t{repl}\n')
with open('check/REPORT.md', 'w', encoding='utf-8', newline='\n') as out:
    out.write('# Scan check report\n\n')
    out.write(f'- Pages with no problems: {ok_pages}\n- Sure corrections applied: {len(sure)}\n- Items for Michael to decide: {len(report)}\n\n')
    out.write('## Applied\n\n' + ('\n'.join(f'- scan page {p}: “{a}” → “{b}”. {n}' for p, a, b, n in sure) or 'None.') + '\n\n')
    out.write('## To decide\n\n' + ('\n'.join(report) or 'None.') + '\n')
print(f'{len(sure)} sure fixes, {len(report)} to decide, {ok_pages} clean pages')
